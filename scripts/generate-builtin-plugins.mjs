import ts from "typescript";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const manifests = fs
  .readdirSync(path.join(root, "plugins"))
  .flatMap((id) => {
    const file = path.join(root, "plugins", id, "jagentdesk-plugin.json");
    if (!fs.existsSync(file)) return [];
    const manifest = JSON.parse(fs.readFileSync(file, "utf8"));
    if (manifest.kind !== "builtin") return [];
    if (
      manifest.id !== id ||
      typeof manifest.defaultEnabled !== "boolean" ||
      !Array.isArray(manifest.requires)
    )
      throw new Error(`Invalid built-in manifest: ${file}`);
    return [manifest];
  })
  .sort((a, b) => a.builtinOrder - b.builtinOrder);
const ids = new Set(manifests.map((m) => m.id));
for (const m of manifests)
  for (const id of m.requires) if (!ids.has(id)) throw new Error(`Unknown dependency: ${id}`);
const banner = "// Generated by scripts/generate-builtin-plugins.mjs. Do not edit.\n";
// Runtime SDK entries have index.server.ts; feature entries use builtinEntrypoints after migration.
const bundled = manifests.filter((m) =>
  fs.existsSync(path.join(root, "plugins", m.id, "index.server.ts")),
);
const staticIds = manifests.filter((m) => !bundled.includes(m)).map((m) => m.id);
const fields = [
  "id",
  "name",
  "description",
  "defaultEnabled",
  "requires",
  "hostCapabilities",
  "command",
];
const data = manifests.map((m) =>
  Object.fromEntries(fields.filter((k) => k in m).map((k) => [k, m[k]])),
);
const outputs = new Map([
  [
    "packages/protocol/src/builtin-plugins.generated.ts",
    banner +
      `export const STATIC_BUILTIN_PLUGIN_IDS = ${JSON.stringify(staticIds)} as const;\n` +
      `export const BUNDLED_PLUGIN_IDS = ${JSON.stringify(bundled.map((m) => m.id))} as const;\n` +
      "export const BUILTIN_PLUGIN_IDS = [...STATIC_BUILTIN_PLUGIN_IDS, ...BUNDLED_PLUGIN_IDS] as const;\n" +
      `export const GENERATED_BUILTIN_MANIFESTS = ${JSON.stringify(data, null, 2)} as const;\n`,
  ],
]);
for (const side of ["server", "client"]) {
  const entries = manifests.filter((m) => m.builtinEntrypoints?.[side]);
  const base =
    side === "server"
      ? "packages/server/src/server/plugins/builtin"
      : "packages/app/src/plugins/builtin";
  const imports = entries
    .map((m, i) => {
      const relative = path
        .relative(base, `plugins/${m.id}/${m.builtinEntrypoints[side]}`)
        .replaceAll(path.sep, "/")
        .replace(/\.tsx?$/, side === "server" ? ".js" : "");
      return `import { register as register${i} } from "${relative}";`;
    })
    .join("\n");
  const type = side === "server" ? "BuiltinServerRegistry" : "BuiltinClientRegistry";
  outputs.set(
    `${base}/load.generated.ts`,
    banner +
      imports +
      `\nimport type { ${type} } from "./host${side === "server" ? ".js" : ""}";\nexport function loadBuiltins(registry: ${type}) {\n` +
      entries.map((m, i) => `  register${i}(registry.forPlugin("${m.id}"));`).join("\n") +
      "\n}\n",
  );
}
let stale = false;
for (const [file, content] of outputs) {
  const target = path.join(root, file);
  // Compare tokens so formatting doesn't invalidate the generated check.
  const normalized = (source) => {
    const sourceFile = ts.createSourceFile("generated.ts", source, ts.ScriptTarget.Latest, true);
    const serialize = (node) => {
      if (node.parent && ts.isPropertyAssignment(node.parent) && node.parent.name === node)
        return ["property", node.text ?? node.getText(sourceFile)];
      const children = [];
      ts.forEachChild(node, (child) => {
        children.push(serialize(child));
      });
      return [node.kind, node.kind === ts.SyntaxKind.SourceFile ? undefined : node.text, children];
    };
    return JSON.stringify(serialize(sourceFile));
  };
  if (process.argv.includes("--check")) {
    if (
      !fs.existsSync(target) ||
      normalized(fs.readFileSync(target, "utf8")) !== normalized(content)
    ) {
      console.error(`Stale: ${file}`);
      stale = true;
    }
  } else {
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, content);
  }
}
if (stale) process.exitCode = 1;
