/** The glyph for a reaction emoji: Unicode for a known shortcode, verbatim text otherwise. */
export function renderEmoji(emoji: string): string {
  const glyph = SHORTCODES[emoji];
  if (glyph) return glyph;
  // Already a literal emoji or an unknown shortcode — show what Figma sent, unmodified.
  return emoji;
}
